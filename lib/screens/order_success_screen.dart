                    const SizedBox(height: 8),
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        const Text('Total Amount Paid:'),
                        Text(currencyFormatter.format(order.totalAmount), style: const TextStyle(fontWeight: FontWeight.bold)),
